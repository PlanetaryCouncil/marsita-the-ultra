#!/usr/bin/env node
/* ==========================================================================
   node site/build.js

   Writes one small HTML file per song from catalog.js:
     site/index.html          the featured song (home page)
     site/<slug>/index.html   every song, at its own link
     site/404.html            unknown links land on the featured song
     site/sitemap.xml

   Each file carries that song's share preview (og:/twitter: tags) — link
   crawlers don't run JavaScript, so this is the only way a shared link to
   /greenland/ shows the Greenland cover instead of a grey box.

   The page content itself is drawn in the browser by assets/site.js, so
   editing links/text in catalog.js works without re-running this. The
   GitHub Action re-runs it on every deploy anyway.

   No dependencies. Node 14+.
   ========================================================================== */
'use strict';

var fs     = require('fs');
var path   = require('path');
var crypto = require('crypto');

var DIR     = __dirname;
var CATALOG = require('./catalog.js');
var SITE    = CATALOG.site;
var SONGS   = CATALOG.songs;


/* ---- sanity checks: fail loudly rather than publish a broken page ------- */
var problems = [];
var warnings = [];
var seen = {};

if (!/\/$/.test(SITE.url)) problems.push('SITE.url must end with a slash: ' + SITE.url);

SONGS.forEach(function (s, i) {
  var where = 'song #' + (i + 1) + ' (' + (s.slug || 'no slug') + ')';
  if (!s.slug || !/^[a-z0-9-]+$/.test(s.slug)) problems.push(where + ': slug must be lowercase letters, digits and dashes');
  if (seen[s.slug]) problems.push(where + ': slug used twice');
  seen[s.slug] = true;
  ['title', 'cover', 'theme', 'share'].forEach(function (k) {
    if (!s[k]) problems.push(where + ': missing ' + k);
  });
  [s.cover, s.share && s.share.image].forEach(function (p) {
    if (p && !/^https?:/.test(p) && !fs.existsSync(path.join(DIR, p))) {
      problems.push(where + ': file not found: site/' + p + '  (run tools/art.py?)');
    }
  });
  (s.blocks || []).forEach(function (b) {
    if (b.type === 'vote') b.candidates.forEach(function (c) {
      if (!/^https?:/.test(c.thumb) && !fs.existsSync(path.join(DIR, c.thumb))) {
        warnings.push(where + ': vote thumbnail missing: site/' + c.thumb);
      }
    });
  });
});
if (!seen[SITE.featured]) problems.push('SITE.featured "' + SITE.featured + '" is not a song slug');
if (/MarsitaTheUltra/.test(JSON.stringify(SITE.socials.filter(function (x) { return x.type === 'telegram'; })))) {
  warnings.push('Telegram link is still the unverified guess — confirm it in catalog.js');
}

warnings.forEach(function (w) { console.warn('  warn  ' + w); });
if (problems.length) {
  problems.forEach(function (p) { console.error('  ERROR ' + p); });
  process.exit(1);
}


/* ---- cache-buster: changes whenever the shared files change ------------- */
var v = crypto.createHash('sha1')
  .update(fs.readFileSync(path.join(DIR, 'catalog.js')))
  .update(fs.readFileSync(path.join(DIR, 'assets/site.js')))
  .update(fs.readFileSync(path.join(DIR, 'assets/site.css')))
  .digest('hex').slice(0, 8);


/* ---- one page ----------------------------------------------------------- */
function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function abs(p) { return /^https?:/.test(p) ? p : SITE.url + p; }

function page(song, base, shareUrl) {
  var t = song.theme || {};
  var sh = song.share || {};
  var title = sh.title || (song.title + ' — ' + SITE.artist);
  var img = abs(sh.image || song.cover);

  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<!-- GENERATED by build.js from catalog.js. Edit catalog.js, not this file. -->',
    '<title>' + esc(song.title + ' — ' + SITE.artist) + '</title>',
    '<meta name="description" content="' + esc(sh.description) + '">',
    '<meta name="theme-color" content="' + esc(t.night || '#0a0616') + '">',
    '<link rel="canonical" href="' + esc(SITE.url + song.slug + '/') + '">',
    '<link rel="icon" href="' + esc(base + song.cover) + '">',
    '',
    '<meta property="og:title" content="' + esc(title) + '">',
    '<meta property="og:description" content="' + esc(sh.description) + '">',
    '<meta property="og:image" content="' + esc(img) + '">',
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta property="og:url" content="' + esc(shareUrl) + '">',
    '<meta property="og:type" content="music.song">',
    '<meta property="og:site_name" content="' + esc(SITE.artist) + '">',
    '<meta name="twitter:card" content="summary_large_image">',
    '<meta name="twitter:title" content="' + esc(title) + '">',
    '<meta name="twitter:description" content="' + esc(sh.description) + '">',
    '<meta name="twitter:image" content="' + esc(img) + '">',
    '',
    '<link rel="stylesheet" href="' + base + 'assets/site.css?v=' + v + '">',
    // paint the song's colours before any script runs — no flash of the wrong theme
    '<style>:root{' + ['a', 'b', 'c', 'night', 'cta'].filter(function (k) { return t[k]; })
      .map(function (k) { return '--' + k + ':' + t[k]; }).join(';') + '}</style>',
    '</head>',
    '<body data-song="' + esc(song.slug) + '" data-base="' + base + '">',
    '<noscript><p style="padding:2rem;text-align:center;font-family:sans-serif">' +
      esc(song.title) + ' — ' + esc(SITE.artist) + '. Everything is on <a href="' + esc(SITE.repo) + '" style="color:inherit">GitHub</a>.</p></noscript>',
    '<script src="' + base + 'catalog.js?v=' + v + '"></script>',
    '<script src="' + base + 'assets/site.js?v=' + v + '"></script>',
    '</body>',
    '</html>',
    ''
  ].join('\n');
}

function write(rel, content) {
  var file = path.join(DIR, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('  wrote site/' + rel);
}


/* ---- write everything --------------------------------------------------- */
var featured = SONGS.filter(function (s) { return s.slug === SITE.featured; })[0];
var rootPath = new URL(SITE.url).pathname;           // '/' on a custom domain

write('index.html', page(featured, '', SITE.url));
write('404.html',   page(featured, rootPath, SITE.url));
SONGS.forEach(function (s) {
  write(s.slug + '/index.html', page(s, '../', SITE.url + s.slug + '/'));
});

// remove pages for songs that were taken out of the catalog
fs.readdirSync(DIR, { withFileTypes: true }).forEach(function (d) {
  if (!d.isDirectory() || seen[d.name]) return;
  var f = path.join(DIR, d.name, 'index.html');
  if (fs.existsSync(f) && /GENERATED by build\.js/.test(fs.readFileSync(f, 'utf8'))) {
    fs.unlinkSync(f);
    try { fs.rmdirSync(path.join(DIR, d.name)); } catch (e) {}
    console.log('  removed site/' + d.name + '/ (no longer in catalog)');
  }
});

write('sitemap.xml',
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  ['<url><loc>' + esc(SITE.url) + '</loc></url>'].concat(SONGS.map(function (s) {
    return '<url><loc>' + esc(SITE.url + s.slug + '/') + '</loc></url>';
  })).map(function (l) { return '  ' + l; }).join('\n') +
  '\n</urlset>\n');

console.log('\n  ' + SONGS.length + ' songs · featured: ' + SITE.featured + ' · ' + SITE.url);
